"use client";
import Link from "next/link";
import { useEffect, useMemo, useState } from "react";
import { ExternalLink, ShieldAlert, Sparkles } from "lucide-react";
import { useData } from "@/lib/client-data";
import type { Article, StaticEntry } from "@/lib/types";
import { CategoryChip, DemoBadge, Empty, ErrorBox, ExamRelevanceBadge, ImportanceBadge, Loading, Stars } from "./ui";
import { ArticleActions } from "./NewsCard";
import QuestionCard from "./QuestionCard";
import { actions } from "@/lib/store";
import { fmtDateTime } from "@/lib/dates";
import { relatedQuestions } from "@/lib/related";
import NewsCard from "./NewsCard";

function Knowledge({ title, entries, kind }: { title: string; entries: StaticEntry[]; kind: "static" | "legal" }) {
  if (!entries.length) return null;
  return (
    <section className="space-y-3">
      <h2 className="h-serif text-xl font-semibold">{title}</h2>
      {entries.map((k) => (
        <div key={k.id} className={`card card-pad ${kind === "legal" ? "border-brand-200 dark:border-brand-900" : ""}`}>
          <h3 className="font-semibold">{k.title}</h3>
          <ul className="mt-2 list-disc space-y-1 pl-5 text-sm text-ink-700 dark:text-ink-200">{k.points.map((p) => <li key={p}>{p}</li>)}</ul>
          {k.explanation && <p className="mt-3 border-t border-ink-100 pt-3 text-sm leading-relaxed dark:border-ink-800"><b>Exam explanation:</b> {k.explanation}</p>}
        </div>))}
    </section>
  );
}

export default function ArticleView({ id }: { id: string }) {
  const { data, error, loading } = useData();
  const a: Article | undefined = useMemo(() => data?.articles.find((x) => x.id === id), [data, id]);
  const [picked, setPicked] = useState<Record<string, number>>({});
  useEffect(() => { if (a) actions.markRead(a.id); }, [a]);
  if (error) return <ErrorBox msg={error} />;
  if (loading || !data) return <Loading />;
  if (!a) return <Empty>Story not found. <Link href="/" className="underline">Back to dashboard</Link></Empty>;

  const statics = data.knowledge.filter((k) => a.staticLinks.includes(k.id));
  const legals = data.knowledge.filter((k) => a.legalLinks.includes(k.id));
  const { own, related } = relatedQuestions(a, data.questions, data.knowledge);
  const qs = [...own, ...related];
  const similar = data.articles.filter((x) => x.id !== a.id && x.category === a.category).sort((x, y) => y.priority_score - x.priority_score).slice(0, 2);

  return (
    <article className="mx-auto max-w-3xl space-y-7">
      <header className="space-y-3">
        <div className="flex flex-wrap items-center gap-1.5"><ImportanceBadge score={a.relevance_score} /><CategoryChip id={a.category} />{a.is_demo && <DemoBadge />}
          {a.ai_generated && <span className="chip" title="Summary generated by AI from the linked sources and checked against them"><Sparkles size={11} />AI-assisted</span>}</div>
        <h1 className="h-serif text-2xl font-bold leading-tight sm:text-4xl">{a.title}</h1>
        <p className="text-xs text-ink-500 dark:text-ink-300">Published {fmtDateTime(a.published_at)} · Priority score {a.priority_score}/100 · Source quality {a.source_quality}/10</p>
        <ExamRelevanceBadge exam={a.exam} />
        <ArticleActions id={a.id} />
      </header>

      {!a.verified && !a.is_demo && <div className="flex gap-2 rounded-xl border border-amber-300 bg-amber-50 p-3 text-sm text-amber-900 dark:border-amber-800 dark:bg-amber-900/20 dark:text-amber-200"><ShieldAlert size={16} className="mt-0.5 shrink-0" />Information could not be independently verified. Open the original source below.</div>}

      <section><h2 className="h-serif mb-2 text-xl font-semibold">What happened?</h2><div className="prose-lite">{a.content.map((p, i) => <p key={i}>{p}</p>)}</div></section>

      <section className="card card-pad border-gold-500/40 bg-gold-400/5">
        <h2 className="h-serif mb-1 text-xl font-semibold">Why this matters</h2><p className="leading-relaxed">{a.whyMatters}</p>
      </section>

      {a.details && (
        <section><h2 className="h-serif mb-2 text-xl font-semibold">At a glance</h2>
          <dl className="card divide-y divide-ink-100 dark:divide-ink-800">{Object.entries(a.details).map(([k, v]) => <div key={k} className="grid grid-cols-3 gap-2 p-3 text-sm"><dt className="font-medium text-ink-500 dark:text-ink-300">{k}</dt><dd className="col-span-2">{v}</dd></div>)}</dl></section>
      )}

      <section><h2 className="h-serif mb-2 text-xl font-semibold">⚡ Exam ready — remember</h2>
        <ol className="card divide-y divide-ink-100 dark:divide-ink-800">{a.keyFacts.map((f, i) => <li key={i} className="flex gap-3 p-3 text-sm"><span className="font-bold text-gold-500">{i + 1}</span>{f}</li>)}</ol></section>

      {a.background && a.background.length > 0 && <section><h2 className="h-serif mb-2 text-xl font-semibold">Background</h2><ul className="list-disc space-y-1 pl-5 text-sm">{a.background.map((b) => <li key={b}>{b}</li>)}</ul></section>}

      <Knowledge title="Static GK connection" entries={statics} kind="static" />
      <Knowledge title="Legal concept connection" entries={legals} kind="legal" />

      {a.examinerAngles && a.examinerAngles.length > 0 && (
        <section><h2 className="h-serif mb-2 text-xl font-semibold">🧐 If I were setting the exam…</h2>
          <ol className="list-decimal space-y-1 pl-5 text-sm">{a.examinerAngles.map((x) => <li key={x}>{x}</li>)}</ol></section>)}

      <section className="card card-pad"><h2 className="h-serif mb-2 text-xl font-semibold">Exam relevance</h2>
        <div className="grid grid-cols-3 gap-2 text-center text-sm">{([["NLSAT", a.exam.nlsat], ["AIAT", a.exam.aiat], ["SSC Law", a.exam.ssc]] as const).map(([k, v]) => <div key={k}><p className="text-xs text-ink-500">{k}</p><p className="h-serif text-2xl font-bold">{v}/10</p><Stars n={v} /></div>)}</div></section>

      <section id="questions" className="space-y-3 scroll-mt-20">
        <h2 className="h-serif text-xl font-semibold">Possible questions</h2>
        {own.length === 0 && qs.length > 0 && <p className="text-xs text-ink-500 dark:text-ink-300">No MCQs have been generated for this story yet — showing practice questions on the linked concepts.</p>}
        {qs.length === 0 && <Empty>No questions available for this story yet. They are generated by the pipeline when an LLM key is configured.</Empty>}
        {qs.map((q, i) => <QuestionCard key={q.id} q={q} index={i} selected={picked[q.id]} onSelect={(n) => setPicked((p) => ({ ...p, [q.id]: n }))} reveal={picked[q.id] !== undefined} />)}
      </section>

      <section><h2 className="h-serif mb-2 text-xl font-semibold">Source</h2>
        <ul className="card divide-y divide-ink-100 dark:divide-ink-800">{a.sources.map((s) => (
          <li key={s.name + s.url} className="flex items-center justify-between gap-3 p-3 text-sm"><span><b>{s.name}</b> <span className="text-xs text-ink-500">quality {s.quality}/10</span></span>
            {s.url && s.url !== "#" ? <a href={s.url} target="_blank" rel="noopener noreferrer" className="btn btn-sm">Original article <ExternalLink size={12} /></a> : <span className="text-xs text-ink-500">demo — no source</span>}</li>))}</ul></section>

      {similar.length > 0 && <section><h2 className="h-serif mb-2 text-xl font-semibold">More in this topic</h2><div className="grid gap-3 sm:grid-cols-2">{similar.map((s) => <NewsCard key={s.id} a={s} showQuiz={false} />)}</div></section>}
    </article>
  );
}
